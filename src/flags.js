/* ------------------------------------------------------------------ *
 * flags.js — the learner disputes a question; the AI judges the dispute.
 *
 * Every flag is kept in two places:
 *   - on the answer inside its session (so it shows when you come back)
 *   - in a single log in this browser ("ql:flags"), which is what the
 *     CSV / JSON export reads — this is the evaluation data for the paper.
 * ------------------------------------------------------------------ */

export const FLAW_TYPES = [
  { key: "key_wrong", label: "The marked answer is wrong" },
  { key: "two_correct", label: "My answer (or another option) is also defensible" },
  { key: "evidence_mismatch", label: "The marked evidence doesn't support the answer" },
  { key: "wrong_level", label: "The PIRLS level label is wrong" },
  { key: "unclear", label: "The question is unclear or ambiguous" },
  { key: "not_in_text", label: "It needs knowledge outside the passage" },
  { key: "other", label: "Something else" },
];

export const VERDICTS = ["upheld", "partly upheld", "not upheld"];

export const FLAG_SCHEMA = {
  type: "object",
  properties: {
    verdict: { type: "string", enum: VERDICTS },
    confirmed: { type: "array", items: { type: "string", enum: FLAW_TYPES.map((f) => f.key) } },
    learner_option_defensible: { type: "boolean" },
    reasoning: { type: "string" },
    fix: { type: "string" },
  },
  required: ["verdict", "confirmed", "learner_option_defensible", "reasoning", "fix"],
};

const LETTERS = ["A", "B", "C", "D", "E", "F"];
const LEVEL_NAMES = {
  1: "Focus on and retrieve explicitly stated information",
  2: "Make straightforward inferences",
  3: "Interpret and integrate ideas and information",
  4: "Evaluate and critique content, language and textual elements",
};

export function buildFlagPrompt({ item, choice, types, argument, passage, evidence }) {
  const opts = item.options
    .map((o, i) => `${LETTERS[i]}. ${o.text}${o.correct ? "   <-- marked correct" : ""}${i === choice ? "   <-- learner chose this" : ""}`)
    .join("\n");
  const typeText = types.length
    ? types.map((k) => FLAW_TYPES.find((f) => f.key === k)?.label || k).join("; ")
    : "(none ticked)";
  const cap = 30000;
  const p = passage.length > cap ? passage.slice(0, cap) + "\n[…truncated…]" : passage;
  return `A reader is disputing a multiple-choice comprehension question that was generated by an AI from the passage below. Judge her dispute fairly and strictly, using ONLY the passage.

Do not agree just because she disagrees, and do not defend the question just because it was generated. Decide on the evidence.

<passage>
${p}
</passage>

THE QUESTION (labelled PIRLS process ${item.level}: ${LEVEL_NAMES[item.level] || "?"})
${item.stem}

${opts}

Evidence span the question was built on: "${evidence || item.anchor || "(none)"}"

WHAT SHE SAYS IS WRONG: ${typeText}
HER ARGUMENT:
<argument>
${argument}
</argument>

Decide:
- "verdict": "upheld" if the question really has the flaw she argues; "partly upheld" if she found a real flaw but part of her argument is wrong; "not upheld" if the question is sound and her argument does not hold.
- "confirmed": the flaw types that really apply, from: ${FLAW_TYPES.map((f) => f.key).join(", ")}. Include a type even if she did not tick it. Empty if none.
- "learner_option_defensible": true only if the option she chose can be defended from the passage as a correct answer.
- "reasoning": at most 60 words, speaking to her as "you". Quote or point to the passage.
- "fix": at most 30 words — how the question should be rewritten, or "No change needed."

Return ONLY JSON:
{"verdict":"...","confirmed":["..."],"learner_option_defensible":false,"reasoning":"...","fix":"..."}`;
}

/* ---------------------------- the log ----------------------------- */

const KEY = "ql:flags";

export function loadFlags() {
  try {
    const raw = localStorage.getItem(KEY);
    const list = raw ? JSON.parse(raw) : [];
    return Array.isArray(list) ? list : [];
  } catch (e) {
    return [];
  }
}

export function saveFlag(rec) {
  try {
    const list = loadFlags().filter((f) => f.id !== rec.id);
    list.push(rec);
    localStorage.setItem(KEY, JSON.stringify(list));
    return true;
  } catch (e) {
    return false;
  }
}

