const COLUMNS = [
  ["flagged_at", (f) => f.flaggedAt],
  ["session_id", (f) => f.sessionId],
  ["candidate_id", (f) => f.candidateId || ""],
  ["run_id", (f) => f.runId || ""],
  ["passage_id", (f) => f.passageId || ""],
  ["passage_title", (f) => f.title],
  ["model", (f) => f.model],
  ["question_id", (f) => f.questionId],
  ["pirls_level", (f) => f.item.level],
  ["stem", (f) => f.item.stem],
  ["option_A", (f) => f.item.options[0]?.text],
  ["option_B", (f) => f.item.options[1]?.text],
  ["option_C", (f) => f.item.options[2]?.text],
  ["option_D", (f) => f.item.options[3]?.text],
  ["keyed_answer", (f) => LETTERS[f.item.options.findIndex((o) => o.correct)]],
  ["learner_choice", (f) => LETTERS[f.choice]],
  ["learner_correct", (f) => (f.learnerCorrect ? "yes" : "no")],
  ["evidence", (f) => f.evidence],
  ["learner_flaw_types", (f) => f.types.join("; ")],
  ["learner_argument", (f) => f.argument],
  ["ai_verdict", (f) => f.judge?.verdict || "not judged"],
  ["ai_confirmed_flaws", (f) => (f.judge?.confirmed || []).join("; ")],
  ["ai_learner_option_defensible", (f) => (f.judge ? (f.judge.learner_option_defensible ? "yes" : "no") : "")],
  ["ai_reasoning", (f) => f.judge?.reasoning],
  ["ai_suggested_fix", (f) => f.judge?.fix],
  /* your own judgement as the human rater, entered in the app */
  /* first verdict = the one given before seeing the AI's (when blind) — use it for Kappa */
  ["human_first_verdict", (f) => humanVerdict(f)],
  ["human_rated_blind", (f) => (f.human?.verdict ? (f.human.blind ? "yes" : "no") : "")],
  ["human_final_verdict", (f) => f.human?.verdict || ""],
  ["human_notes", (f) => f.human?.notes || ""],
  ["ai_human_agree", (f) => (humanVerdict(f) && f.judge ? (humanVerdict(f) === f.judge.verdict ? "yes" : "no") : "")],
];

const csvCell = (v) => {
  const s = v == null ? "" : String(v);
  return /[",\n\r]/.test(s) ? '"' + s.replace(/"/g, '""') + '"' : s;
};

function download(name, text, type) {
  const blob = new Blob([text], { type });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = name;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

function humanVerdict(f) {
  return f.human?.firstVerdict || f.human?.verdict || "";
}

/* AI–human agreement over the flags you have rated (first verdicts) */
export function agreement() {
  const rated = loadFlags().filter((f) => humanVerdict(f) && f.judge);
  return { rated: rated.length, agree: rated.filter((f) => humanVerdict(f) === f.judge.verdict).length };
}

export function exportFlagsCSV() {
  const list = loadFlags();
  const rows = [COLUMNS.map((c) => c[0]).join(",")].concat(
    list.map((f) => COLUMNS.map(([, get]) => csvCell(get(f))).join(","))
  );
  /* BOM so Excel opens the UTF-8 correctly */
  download(`question-flags-${new Date().toISOString().slice(0, 10)}.csv`, "﻿" + rows.join("\r\n"), "text/csv");
}

export function exportFlagsJSON() {
  download(`question-flags-${new Date().toISOString().slice(0, 10)}.json`, JSON.stringify(loadFlags(), null, 2), "application/json");
}
